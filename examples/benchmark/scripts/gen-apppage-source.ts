#!/usr/bin/env bun
/**
 * Emits `src/impl/apppage-pyreon.tsx` — the Pyreon half of the app-page
 * hydration scenario, as STATICALLY COMPOSED JSX.
 *
 * Why generated rather than hand-written: the page is 320 component instances
 * (20 sections x [1 header + 15 form rows]). Spelling them out is what makes
 * the compiler emit a root `_tpl` per component, which is the shape under
 * measurement; a `.map()` would lower to a slot and (measured) does NOT adopt
 * even after the fix. Generating from the SAME descriptor the other
 * frameworks build from keeps the structure provably identical across arms —
 * nothing here is hand-tuned per framework.
 */
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { APPPAGE_SECTIONS, APPPAGE_ROWS } from '../src/impl/apppage-descriptor'

const lines: string[] = []
for (let s = 0; s < APPPAGE_SECTIONS; s++) {
  lines.push(`        <SectionHeader title="Section ${s}" hint="configure ${s}" />`)
  for (let r = 0; r < APPPAGE_ROWS; r++) {
    lines.push(
      `        <FormRow label="Field ${s}.${r}" name="f${s}_${r}" value="v${s}_${r}" hint="help ${s}.${r}" />`,
    )
  }
}

const src = `/**
 * GENERATED by scripts/gen-apppage-source.ts — do not edit by hand.
 *
 * Pyreon app-page hydration target: ${APPPAGE_SECTIONS} sections x
 * [1 SectionHeader + ${APPPAGE_ROWS} FormRow] = ${APPPAGE_SECTIONS * (1 + APPPAGE_ROWS)}
 * statically-composed component instances. Each component's root is a plain
 * templatized element subtree, so hydration reaches it through
 * hydrateComponent -> root \`_tpl\`.
 */
export function SectionHeader(props: { title: string; hint: string }) {
  return (
    <div class="sec-hd">
      <h2 class="sec-title">{props.title}</h2>
      <span class="sec-hint">{props.hint}</span>
    </div>
  )
}

export function FormRow(props: { label: string; name: string; value: string; hint: string }) {
  return (
    <div class="row">
      <label class="row-label">{props.label}</label>
      <div class="row-ctl">
        <input class="row-input" type="text" name={props.name} value={props.value} />
        <small class="row-hint">{props.hint}</small>
      </div>
    </div>
  )
}

export function AppPage(props: { onSelect: (id: string) => void; selected: () => string | null }) {
  return (
    <div class="page">
      <div class="page-hd">
        <h1 class="page-title">Settings</h1>
        <button
          type="button"
          class={() => (props.selected() === 'save' ? 'page-save active' : 'page-save')}
          onClick={() => props.onSelect('save')}
        >
          Save
        </button>
      </div>
${lines.join('\n')}
    </div>
  )
}
`

const out = join(import.meta.dirname, '../src/impl/apppage-pyreon.tsx')
writeFileSync(out, src)
console.log(
  `[gen-apppage-source] wrote ${out} (${APPPAGE_SECTIONS * (1 + APPPAGE_ROWS)} component instances)`,
)
