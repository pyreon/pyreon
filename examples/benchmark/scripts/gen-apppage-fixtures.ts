#!/usr/bin/env bun
/**
 * Generates per-framework SSR HTML for the app-page hydration scenario.
 *
 * Each framework's HTML comes from its OWN server renderer over the shared
 * page module — the only sound setup, since every framework's hydration only
 * adopts nodes when the markup matches what its own renderer emits.
 *
 * The load-bearing gate here is the MARKUP EQUALITY check: after stripping
 * each framework's private hydration annotations and normalising attribute
 * order, all four fixtures must be byte-identical. Without it a framework
 * could quietly be hydrating a smaller or differently-shaped page and post a
 * fast, meaningless number.
 *
 * Output: public/apppage-fixtures.json (gitignored — regenerated by the
 * driver before `vite build`).
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

process.env.NODE_ENV = 'production'

const { renderToString: pyreonRender } = await import('@pyreon/runtime-server')
const { renderToString: reactRender } = await import('react-dom/server')
const { renderToString: preactRender } = await import('preact-render-to-string')
const { renderToString: vueRender } = await import('@vue/server-renderer')
const { createSSRApp } = await import('vue')

const { pyreonAppPage, reactAppPage, preactAppPage, vueAppPage } = await import(
  '../src/impl/apppage-shared'
)
const { APPPAGE_COMPONENTS } = await import('../src/impl/apppage-descriptor')

const pyreonHtml = await pyreonRender(pyreonAppPage(() => null))
const reactHtml = reactRender(reactAppPage(null, () => {}))
const preactHtml = preactRender(preactAppPage(null, () => {}))
const vueHtml = await vueRender(createSSRApp(vueAppPage().component))

const all = { pyreon: pyreonHtml, react: reactHtml, preact: preactHtml, vue: vueHtml }

/** Strip framework-private hydration annotations + normalise attr spelling so
 * the four fixtures are comparable as RENDERED STRUCTURE. */
function normalise(html: string): string {
  return html
    .replace(/<!--(\[|\]|\/?\$|-)-->/g, '') // Vue fragment + Pyreon accessor markers
    .replace(/<!--[^>]*-->/g, '') // any remaining comment markers
    .replace(/\s+data-reactroot="[^"]*"/g, '')
    .replace(/<!---->/g, '')
    .replace(/\s+/g, ' ')
    // Void-element serialisation style only: `<input … />` vs `<input …/>` vs
    // `<input …>`. Not a structural difference — the parsed DOM is identical.
    .replace(/\s*\/?>/g, '>')
    .trim()
}

const norm = Object.fromEntries(Object.entries(all).map(([k, v]) => [k, normalise(v)]))
const ref = norm.pyreon!
for (const [name, h] of Object.entries(norm)) {
  if (h !== ref) {
    // Report the first divergence with context — a silent mismatch here is the
    // difference between a benchmark and a fabrication.
    let i = 0
    while (i < Math.min(h.length, ref.length) && h[i] === ref[i]) i++
    throw new Error(
      `[gen-apppage-fixtures] ${name} markup differs from pyreon at offset ${i}\n` +
        `  pyreon: …${ref.slice(Math.max(0, i - 60), i + 60)}…\n` +
        `  ${name}: …${h.slice(Math.max(0, i - 60), i + 60)}…`,
    )
  }
}

// Structural sanity: the component count must actually be on the page.
const rowCount = (ref.match(/class="row"/g) ?? []).length
const hdCount = (ref.match(/class="sec-hd"/g) ?? []).length
if (rowCount + hdCount !== APPPAGE_COMPONENTS) {
  throw new Error(
    `[gen-apppage-fixtures] expected ${APPPAGE_COMPONENTS} component instances, got ${rowCount + hdCount}`,
  )
}

const dir = join(import.meta.dirname, '../public')
mkdirSync(dir, { recursive: true })
writeFileSync(join(dir, 'apppage-fixtures.json'), JSON.stringify({ html: all }))
console.log(
  `[gen-apppage-fixtures] wrote 4 fixtures — markup IDENTICAL across frameworks ` +
    `(${APPPAGE_COMPONENTS} components, ${hdCount} headers + ${rowCount} rows; ` +
    `pyreon=${(pyreonHtml.length / 1024).toFixed(1)}KB react=${(reactHtml.length / 1024).toFixed(1)}KB ` +
    `preact=${(preactHtml.length / 1024).toFixed(1)}KB vue=${(vueHtml.length / 1024).toFixed(1)}KB)`,
)
