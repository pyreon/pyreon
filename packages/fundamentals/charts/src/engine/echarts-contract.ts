/**
 * The ECharts option contract, measured.
 *
 * `option-key-totality.test.ts` enumerates every key the installed `echarts`
 * types define — the top-level `EChartsOption` keys and each series type's
 * keys — with the TypeScript checker, and requires each to be exactly one of:
 *
 *  - READ by the facade (listed in a facade `KNOWN_*` set AND read by code —
 *    a known key nothing reads is a silent drop, and fails the test);
 *  - INERT: it changes nothing a reader can see (a performance hint, an
 *    internal discriminator), with the reason stated below;
 *  - a GAP, filed under the capability-ledger row that owns it. A row with a
 *    gap here cannot be complete on the web.
 *
 * When a key is implemented it must leave the gap table (the test fails on a
 * stale entry), so this file shrinks as parity grows. An `echarts` upgrade
 * fails the version pin until the new version's keys are classified. The
 * tables below are GENERATED — `bun run gen:contract` — so edit the
 * classification rules in `scripts/gen-echarts-contract.ts`, not the tables.
 *
 * Scope, stated so it is not over-read: this covers top-level and series-level
 * keys, per series type, on each type's default coordinate system. Nested keys
 * (`tooltip.*`, `xAxis.*`) and a type's alternate coordinate systems are
 * tracked by their own rows' gap prose until they get an instrument of this
 * kind.
 */
