// Top-level navigation primitives — `<Tabs>` / `<Tab>` and `<Split>`.
//
// These are the app-STRUCTURE primitives: a tab bar that keeps each tab's
// state, and a list/detail split that collapses to one pane on a narrow
// window. They are router-AGNOSTIC (same as `<Link>`) — the selected tab and
// the visible pane are ordinary signals the app owns, so a tab can host
// anything, including its own screen stack.

import type { VNodeChild } from '@pyreon/core'
import type { ChildrenProp, HtmlPassthroughProps, ValueOrSignal } from './shared'

/**
 * `<Tabs>` — top-level tab navigation. Children are `<Tab>` elements.
 *
 * Per-platform mapping:
 * - Web: WAI-ARIA tabs (`role="tablist"` / `"tab"` / `"tabpanel"`). A bottom
 *   bar below 600px of viewport width, a side rail at 600px and wider.
 * - iOS: `TabView(selection:)` — the tab bar on iPhone; on iOS 18+ the
 *   `.sidebarAdaptable` style, which iPadOS renders as a sidebar.
 * - Android: Material `BottomNavigation` below 600dp of window width,
 *   `NavigationRail` at 600dp and wider (the `useSizeClass()` breakpoint).
 *
 * Every visited tab stays mounted while another one is shown, so a tab's
 * scroll position, typed text and local state survive switching away and
 * back — on all three targets.
 */
export type TabsProps = TabsSignalProps | TabsRouterProps

interface TabsBaseProps extends HtmlPassthroughProps {
  /** `<Tab>` elements, written directly (not generated by a loop). */
  children?: VNodeChild
}

/** `<Tabs value onChange>` — the selection is a signal the app owns. */
export interface TabsSignalProps extends TabsBaseProps {
  /** The selected tab's `value`. A bare signal binds two-way on native. */
  value: ValueOrSignal<string>
  /** Called with the `value` of the tab the user selected. */
  onChange: (next: string) => void
  router?: undefined
}

/**
 * `<Tabs router={router}>` — the selection is the router's active tab, and
 * each tab has its own back stack (`createRouter({ tabs })` from
 * `@pyreon/router`). Each `<Tab value>` names a configured tab; put a
 * `<RouterView />` inside it to show that tab's stack. Selecting the tab that
 * is already active pops it to its root.
 */
export interface TabsRouterProps extends TabsBaseProps {
  /** A router created with `tabs` — `createRouter({ routes, tabs })`. */
  router: TabsRouter
  value?: undefined
  onChange?: undefined
}

/**
 * The part of a `@pyreon/router` router that `<Tabs router>` drives. Typed
 * structurally so this package needs no router dependency (`<Link>` is
 * router-agnostic the same way).
 */
export interface TabsRouter {
  /** The active tab's name (reactive), `undefined` when the router has no tabs. */
  activeTab(): string | undefined
  /** Select a tab; selecting the active one pops it to its root. */
  selectTab(name: string): unknown
  /** Render a tab's panel so the views inside it read THAT tab's stack. */
  withTab(name: string, render: () => VNodeChild): VNodeChild
}

/**
 * `<Tab>` — one entry of a `<Tabs>`. Its children are the tab's content.
 *
 * `value`, `label` and `icon` must be string LITERALS: the native compilers
 * build the tab bar at compile time. `icon` is a canonical `<Icon>` name.
 * `data-testid` identifies the tab's bar ITEM (web `button`, Android
 * navigation item); iOS gives a tab bar button no identifier, so query it by
 * its label there.
 */
export interface TabProps extends ChildrenProp {
  value: string
  label: string
  icon?: string
  'data-testid'?: string
}

/**
 * `<Split>` — list/detail layout. `sidebar` is the list; the children are the
 * detail.
 *
 * Per-platform mapping:
 * - Web: two columns at 600px of viewport width and wider; below it, ONE pane
 *   — the sidebar, or the detail (with a back button) while `showDetail`.
 * - iOS: `NavigationSplitView` in a regular-width window; in a compact one,
 *   the sidebar with the detail pushed onto a navigation stack while
 *   `showDetail` (system back button and swipe-back call `onBack`).
 * - Android: two panes at 600dp of window width and wider; below it, one
 *   pane, with the system back gesture calling `onBack` from the detail.
 *
 * `showDetail` only decides what a NARROW window shows; a wide one always
 * shows both panes, so render a placeholder detail when nothing is selected.
 */
export interface SplitProps extends ChildrenProp, HtmlPassthroughProps {
  /** The list pane. */
  sidebar: VNodeChild
  /** On a narrow window: show the detail (true) or the sidebar (false). */
  showDetail: ValueOrSignal<boolean>
  /** Called when the user navigates back from the detail on a narrow window. */
  onBack: () => void
  /** Web only: the compact back button's text. Defaults to "Back". */
  backLabel?: string
}
