import path from 'node:path'
import { emitRuntimeSlugHelper } from './_shared/derive-slug'
import { toJsExpression } from './pipeline/serialize'
import type { ContentConfig } from './types'

// ─── virtual:zero-content/collections module renderer ──────────────────────
//
// Emitted body imports `_setRegistry` from the runtime and registers a
// per-collection metadata bundle. Each collection's loader map uses
// `import.meta.glob` to lazy-load every entry — Vite splits each
// markdown module into a per-route chunk so cold pages don't pull
// content data into the initial bundle.
//
// We rely on Vite's resolution of `import.meta.glob` at consumer build
// time: the path string in the emitted source is a relative path from
// the virtual module's "logical" location (we use the project root for
// stability) to the collection's content dir.

/**
 * Id prefix of a collection's metadata module: `virtual:zero-content/meta/<name>`
 * exports `entries` — slug, parsed frontmatter, headings, word count and
 * excerpt of every entry, and no bodies. Listings load this one chunk.
 */
export const VIRTUAL_META_PREFIX = 'virtual:zero-content/meta/'

export interface RenderVirtualCollectionsArgs {
  config: ContentConfig
  /** Vite root, used to compute the import.meta.glob path. */
  root: string
  /**
   * Per collection, the files a production build leaves out (unpublished
   * entries of an `unpublished: 'omit'` collection), as absolute paths.
   * Each becomes a negative `import.meta.glob` pattern, so the file is
   * never bundled — not just hidden from queries.
   */
  exclude?: Record<string, readonly string[]>
  /**
   * The instant the build decided publish state at (epoch ms). Emitted as
   * `publishCutoff` on every collection that has exclusions, so the
   * runtime's `getCollection` judges scheduled entries against the same
   * instant the bundle was cut at, not the visitor's clock.
   */
  publishCutoff?: number
}

/**
 * Render the virtual `:zero-content/collections` module body. Pure —
 * the Vite plugin's `load` hook returns this string.
 *
 * @internal exported for testing
 */
export function renderVirtualCollections(
  args: RenderVirtualCollectionsArgs,
): string {
  const collectionEntries = Object.entries(args.config.collections)
  if (collectionEntries.length === 0) {
    return `// Auto-generated by @pyreon/zero-content. No collections defined.
import { _setRegistry } from '@pyreon/zero-content'
_setRegistry({})
`
  }
  const lines: string[] = []
  for (const [name, def] of collectionEntries) {
    const collectionDir = def.path ?? `src/content/${name}`
    // Glob is relative to the importing module. Use absolute path
    // resolved against root so the user's `path` override works
    // regardless of where the virtual module is "located".
    const absDir = path.isAbsolute(collectionDir)
      ? collectionDir
      : path.join(args.root, collectionDir)
    const globPath = '/' + path.relative(args.root, absDir).split(path.sep).join('/') + '/**/*.{md,mdx}'
    const excluded = (args.exclude?.[name] ?? [])
      .map((file) => '!/' + path.relative(args.root, file).split(path.sep).join('/'))
      .sort()
    const globArg = excluded.length > 0 ? [globPath, ...excluded] : globPath
    lines.push(
      `const __${name}_modules = import.meta.glob(${JSON.stringify(globArg)})`,
    )
  }

  const registryLines: string[] = []
  for (const [name, def] of collectionEntries) {
    const collectionDir = def.path ?? `src/content/${name}`
    const absDir = path.isAbsolute(collectionDir)
      ? collectionDir
      : path.join(args.root, collectionDir)
    const relAbsDir = '/' + path.relative(args.root, absDir).split(path.sep).join('/')
    const publishLines =
      (def.publishDate !== undefined
        ? `\n    publishDate: ${JSON.stringify(def.publishDate)},`
        : '') +
      (args.exclude?.[name] !== undefined && args.publishCutoff !== undefined
        ? `\n    publishCutoff: ${JSON.stringify(args.publishCutoff)},`
        : '')
    // Slug derivation matches `deriveSlug` in parse.ts: strip ext + `/index`
    registryLines.push(
      `  ${JSON.stringify(name)}: {
    name: ${JSON.stringify(name)},
    type: ${JSON.stringify(def.type)},${publishLines}
    meta: () => import(${JSON.stringify(VIRTUAL_META_PREFIX + name)}),
    loaders: Object.fromEntries(
      Object.entries(__${name}_modules).map(([file, loader]) => [
        __zcSlug(file, ${JSON.stringify(relAbsDir)}),
        loader,
      ]),
    ),
  }`,
    )
  }

  return `// Auto-generated by @pyreon/zero-content. Do not edit.
import { _setRegistry } from '@pyreon/zero-content'

${lines.join('\n')}

${emitRuntimeSlugHelper()}

_setRegistry({
${registryLines.join(',\n')}
})

export {}
`
}

/** One entry of a rendered metadata module. */
export interface MetaModuleEntry {
  slug: string
  /** Parsed frontmatter (the collection schema's output). */
  frontmatter: Record<string, unknown>
  headings: ReadonlyArray<{ level: number; text: string; slug: string }>
  wordCount: number
  excerpt: string
}

/**
 * Render a collection's metadata module. Pure. Entries are sorted by slug so
 * the output is deterministic; the frontmatter is written as a JS
 * expression so a schema's `Date` output survives.
 *
 * @internal exported for the plugin + tests
 */
export function renderMetaModule(entries: readonly MetaModuleEntry[]): string {
  const sorted = [...entries].sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0))
  const lines = sorted.map(
    (e) =>
      `  { slug: ${JSON.stringify(e.slug)}, frontmatter: ${toJsExpression(e.frontmatter, `${e.slug}.frontmatter`)}, headings: ${JSON.stringify(e.headings)}, wordCount: ${e.wordCount}, excerpt: ${JSON.stringify(e.excerpt)} },`,
  )
  return `// Auto-generated by @pyreon/zero-content. Do not edit.
// Listing metadata only: no entry bodies are reachable from this module.
export const entries = [
${lines.join('\n')}
]
`
}
