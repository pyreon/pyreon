/**
 * `Intl` on native, checked against the WEB (#3980).
 *
 * Each case in `intl-cases.ts` goes through the SAME planner the compiler
 * uses (`planDateTime` / `planNumber` → `planArguments`), becomes a real
 * `PyreonDateTimeFormat(…)` / `PyreonNumberFormat(…)` call, is compiled with the
 * shipped `PyreonIntl.swift` and RUN — and its output is compared with what
 * Node's `Intl` (V8, the Chrome engine) prints for the same case.
 *
 * - STABLE cases must match exactly.
 * - The SWEEP is reported, with a loose tripwire: a broken skeleton mapping or
 *   a lost rounding mode moves it from "a CLDR-version gap" to "most cases",
 *   which the tripwire catches without pretending the data gap is a bug.
 * - When JavaScriptCore is present (every Mac), the same sweep is compared with
 *   Safari's `Intl` too. That comparison is the one that should be ~exact: JSC
 *   and Foundation read the same Apple CLDR data, so it isolates the lowering
 *   from the data.
 *
 * The Android half of the table runs on the emulator
 * (`examples/native-tasks-android` → `IntlDifferentialTest`), because Android's
 * formatters are `android.icu` and exist only on a device.
 */

import { execFileSync, spawnSync } from 'node:child_process'
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { beforeAll, describe, expect, it } from 'vitest'
import { planArguments, planDateTime, planNumber, type IntlOptionInput } from '../intl-options'
import { isSwiftcAvailable } from '../validate'
import { STABLE, SWEEP, webFormat, type IntlCase } from './intl-cases'

const RUNTIME = resolve(import.meta.dirname, '../../../runtime-swift/Sources/PyreonRuntime/PyreonIntl.swift')
const JSC = '/System/Library/Frameworks/JavaScriptCore.framework/Versions/Current/Helpers/jsc'

const swiftString = (s: string): string => JSON.stringify(s)

/** The runtime call the compiler would emit for a case, through the compiler's own planner. */
export function swiftCall(c: IntlCase): string {
  const args = caseArguments(c).map(([n, v]) => `${n}: ${typeof v === 'string' ? swiftString(v) : String(v)}`)
  const ctor = c.kind === 'number' ? 'PyreonNumberFormat' : 'PyreonDateTimeFormat'
  return `${ctor}(${args.join(', ')}).format(${c.value} as Double)`
}

/** The runtime arguments a case plans to, through the compiler's own planner. */
function caseArguments(c: IntlCase): Array<readonly [string, string | number | boolean]> {
  const options = new Map<string, IntlOptionInput>(
    Object.entries(c.options).map(([k, v]) => [k, { kind: 'static', value: v }]),
  )
  const result =
    c.kind === 'number' ? planNumber('case', options) : planDateTime(c.entry ?? 'DateTimeFormat', options)
  if (result.plan === null || result.warnings.length > 0) {
    throw new Error(`case ${c.id} is outside the supported subset: ${result.warnings.join(' / ')}`)
  }
  const out: Array<readonly [string, string | number | boolean]> = [['locale', c.locale]]
  for (const [name, v] of planArguments(result.plan)) {
    if (v.kind !== 'static') throw new Error(`case ${c.id}: a dynamic option in the table`)
    out.push([name, v.value])
  }
  return out
}

const ANDROID_CASES = resolve(
  import.meta.dirname,
  '../../../../../examples/native-tasks-android/app/src/androidTest/kotlin/com/pyreon/IntlDifferentialCases.kt',
)

/**
 * The Android half of the table as Kotlin, for the emulator's
 * `IntlDifferentialTest`. GENERATED from `intl-cases.ts` + Node's output, and
 * checked for freshness below — the oracle strings are V8's, so the file must
 * be regenerated (`PYREON_UPDATE_INTL_CASES=1`) when the table or Node changes.
 */
export function androidCasesSource(): string {
  const kt = (s: string) => JSON.stringify(s).replace(/\$/g, '\\$')
  const row = (c: IntlCase, stable: boolean): string => {
    const args = caseArguments(c)
      .map(([n, v]) => `${n} = ${typeof v === 'string' ? kt(v) : String(v)}`)
      .join(', ')
    const ctor = c.kind === 'number' ? 'PyreonNumberFormat' : 'PyreonDateTimeFormat'
    return `    IntlCase(${kt(c.id)}, ${stable}, ${kt(c.kind)}, ${kt(webFormat(c))}) { ${ctor}(${args}).format(${Number.isInteger(c.value) ? `${c.value}.0` : String(c.value)}) },`
  }
  return [
    '// GENERATED by packages/native/compiler/src/tests/intl-differential.test.ts from intl-cases.ts —',
    '// do not edit. The expected strings are what Node\'s Intl (V8) prints; regenerate with',
    '// PYREON_UPDATE_INTL_CASES=1 bunx vitest run src/tests/intl-differential.test.ts (in packages/native/compiler).',
    'package com.pyreon',
    '',
    'import com.pyreon.runtime.PyreonDateTimeFormat',
    'import com.pyreon.runtime.PyreonNumberFormat',
    '',
    'class IntlCase(val id: String, val stable: Boolean, val kind: String, val web: String, val native: () -> String)',
    '',
    `/** Node ${process.versions.node}, ICU ${process.versions.icu}, CLDR ${process.versions.cldr}. */`,
    'val INTL_CASES: List<IntlCase> = listOf(',
    ...STABLE.map((c) => row(c, true)),
    ...SWEEP.map((c) => row(c, false)),
    ')',
    '',
  ].join('\n')
}

describe('the Android table', () => {
  it('is current with intl-cases.ts and the web oracle', () => {
    const fresh = androidCasesSource()
    if (process.env.PYREON_UPDATE_INTL_CASES === '1') writeFileSync(ANDROID_CASES, fresh, 'utf8')
    // Compare without the toolchain line: a different Node patch release must
    // not fail the gate unless the STRINGS moved.
    const strip = (s: string) => s.replace(/^\/\*\* Node .*$/m, '')
    expect(strip(readFileSync(ANDROID_CASES, 'utf8'))).toBe(strip(fresh))
  })
})

/** Run every case through the real Swift runtime; one output line per case. */
function runSwift(cases: readonly IntlCase[]): Map<string, string> {
  const dir = mkdtempSync(join(tmpdir(), 'pyreon-intl-'))
  try {
    const main = cases
      .map((c) => `print(${swiftString(c.id)} + "\\u{1F}" + ${swiftCall(c)}.replacingOccurrences(of: "\\n", with: "\\\\n"))`)
      .join('\n')
    const mainPath = join(dir, 'main.swift')
    writeFileSync(mainPath, `import Foundation\n${main}\n`, 'utf8')
    const bin = join(dir, 'intl-probe')
    execFileSync('swiftc', ['-O', '-o', bin, mainPath, RUNTIME], { stdio: 'pipe' })
    const out = execFileSync(bin, [], { encoding: 'utf8' })
    const map = new Map<string, string>()
    for (const line of out.split('\n')) {
      const i = line.indexOf('\u001F')
      if (i > 0) map.set(line.slice(0, i), line.slice(i + 1).replace(/\\n/g, '\n'))
    }
    return map
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

/** Safari's `Intl` for the same cases, with V8's U+202F → space adjustment applied. */
function runJsc(cases: readonly IntlCase[]): Map<string, string> {
  const dir = mkdtempSync(join(tmpdir(), 'pyreon-intl-jsc-'))
  try {
    const body = `const cases = ${JSON.stringify(cases)};
for (const c of cases) {
  const d = new Date(c.value);
  let s;
  if (c.kind === 'number') s = new Intl.NumberFormat(c.locale, c.options).format(c.value);
  else if (c.entry === 'toLocaleDateString') s = d.toLocaleDateString(c.locale, c.options);
  else if (c.entry === 'toLocaleTimeString') s = d.toLocaleTimeString(c.locale, c.options);
  else if (c.entry === 'toLocaleString') s = d.toLocaleString(c.locale, c.options);
  else s = new Intl.DateTimeFormat(c.locale, c.options).format(c.value);
  print(c.id + '\\u001F' + (c.kind === 'number' ? s : s.replace(/\\u202f/g, ' ')));
}`
    const path = join(dir, 'probe.js')
    writeFileSync(path, body, 'utf8')
    const out = spawnSync(JSC, [path], { encoding: 'utf8' }).stdout
    const map = new Map<string, string>()
    for (const line of out.split('\n')) {
      const i = line.indexOf('\u001F')
      if (i > 0) map.set(line.slice(0, i), line.slice(i + 1))
    }
    return map
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

const isDarwin = process.platform === 'darwin'

describe.runIf(isDarwin && isSwiftcAvailable())('Intl on iOS — the runtime against the web', () => {
  let swift = new Map<string, string>()
  beforeAll(() => {
    swift = runSwift([...STABLE, ...SWEEP])
  }, 300_000)

  it('runs every case', () => {
    // An empty map would make every comparison below vacuous.
    expect(swift.size).toBe(STABLE.length + SWEEP.length)
  })

  it.each(STABLE)('STABLE $id matches the web exactly', (c) => {
    expect(swift.get(c.id)).toBe(webFormat(c))
  })

  it('the sweep differs from V8 only by CLDR data, not by the lowering', () => {
    const dates = SWEEP.filter((c) => c.kind === 'datetime')
    const numbers = SWEEP.filter((c) => c.kind === 'number')
    const off = (cs: readonly IntlCase[]) => cs.filter((c) => swift.get(c.id) !== webFormat(c))
    const dateOff = off(dates)
    const numberOff = off(numbers)
    console.info(
      `[intl-differential] iOS vs V8: dates ${dateOff.length}/${dates.length} differ, numbers ${numberOff.length}/${numbers.length} differ`,
    )
    // Tripwires, above the measured CLDR gap (dates 19%, numbers 1% on macOS 26)
    // and far below what a broken lowering produces (a lost skeleton or rounding
    // mode moves most of the sweep).
    expect(dateOff.length / dates.length).toBeLessThan(0.3)
    expect(numberOff.length / numbers.length).toBeLessThan(0.12)
  })

  it.runIf(existsSync(JSC))('…and matches Safari, which reads the same CLDR data, almost exactly', () => {
    const jsc = runJsc([...STABLE, ...SWEEP])
    const all = [...STABLE, ...SWEEP]
    const off = all.filter((c) => jsc.get(c.id) !== undefined && swift.get(c.id) !== jsc.get(c.id))
    console.info(`[intl-differential] iOS vs JavaScriptCore: ${off.length}/${all.length} differ`)
    if (off.length > 0) {
      console.info(off.slice(0, 8).map((c) => `  ${c.id}: native ${JSON.stringify(swift.get(c.id))} / jsc ${JSON.stringify(jsc.get(c.id))}`).join('\n'))
    }
    expect(off.length / all.length).toBeLessThan(0.03)
  })
})
