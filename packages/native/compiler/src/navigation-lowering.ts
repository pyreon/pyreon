/**
 * Target-neutral reading of the `<Tabs>` / `<Tab>` and `<Split>` navigation
 * primitives, shared by `emit-swift.ts` and `emit-kotlin.ts` so both targets
 * accept, reject and NAME exactly the same shapes.
 *
 * The native tab bar is built at compile time (SwiftUI `[PyreonTabItem]`,
 * Compose `listOf(PyreonTabItem(…))`) and each tab's content becomes one
 * `case` / `when` branch keyed on the tab's `value`, so a tab must be a
 * literal `<Tab value="…">` written directly inside `<Tabs>`. Anything else —
 * a `<For>`, a helper call, a computed value — is named in a warning rather
 * than dropped, because a tab that silently vanishes from the bar is a
 * screen the user can never reach.
 */

import { ICON_MAP } from './canonical-primitives'
import type { AttrIR, ChildIR, ExprIR } from './types'

type JsxElement = Extract<ExprIR, { kind: 'jsx-element' }>

export interface TabPlan {
  readonly value: string
  /** A literal label, or the expression for a computed one. */
  readonly label: { readonly kind: 'literal'; readonly text: string } | { readonly kind: 'expr'; readonly expr: ExprIR }
  /** Resolved glyphs, or undefined when the tab has no icon. */
  readonly icon: { readonly sf: string; readonly material: string } | undefined
  readonly testId: string | undefined
  readonly children: readonly ChildIR[]
}

const attrNamed = (e: JsxElement, name: string): Extract<AttrIR, { kind: 'attr' }> | undefined =>
  e.attrs.find((a): a is Extract<AttrIR, { kind: 'attr' }> => a.kind === 'attr' && a.name === name)

const literalString = (a: Extract<AttrIR, { kind: 'attr' }> | undefined): string | undefined =>
  a !== undefined && a.value.kind === 'literal' && typeof a.value.value === 'string'
    ? a.value.value
    : undefined

/** JSX whitespace between the `<Tab>` elements carries no meaning. */
const isBlankText = (c: ChildIR): boolean => c.kind === 'text' && c.value.trim() === ''

/**
 * The `<Tab>` entries of a `<Tabs>`, plus a warning for every child that
 * cannot become one. Never throws; an unusable `<Tabs>` yields zero tabs.
 */
export function planTabs(e: JsxElement): { tabs: TabPlan[]; warnings: string[] } {
  const tabs: TabPlan[] = []
  const warnings: string[] = []
  const seen = new Set<string>()
  for (const child of e.children) {
    if (isBlankText(child)) continue
    const el = child.kind === 'expr' && child.expr.kind === 'jsx-element' ? child.expr : undefined
    if (el === undefined || el.tag !== 'Tab') {
      warnings.push(
        `<Tabs>: every child must be a literal <Tab value="…" label="…"> written directly inside it — this ${
          el !== undefined ? `<${el.tag}>` : child.kind === 'text' ? 'text' : `\`${child.expr.kind}\` expression`
        } is DROPPED on iOS/Android, because the native tab bar is built at compile time (a tab generated by <For> or a helper has no compile-time entry). Write each <Tab> out.`,
      )
      continue
    }
    const value = literalString(attrNamed(el, 'value'))
    if (value === undefined) {
      warnings.push(
        '<Tab>: `value` must be a string LITERAL on iOS/Android — it becomes the `case` / `when` branch that renders the tab, so a computed value has nothing to match. This tab is DROPPED on native.',
      )
      continue
    }
    if (seen.has(value)) {
      warnings.push(`<Tab value=${JSON.stringify(value)}>: a second tab with the same value is DROPPED — each tab needs a distinct value to be selectable.`)
      continue
    }
    seen.add(value)
    const labelAttr = attrNamed(el, 'label')
    const labelText = literalString(labelAttr)
    let label: TabPlan['label']
    if (labelText !== undefined) label = { kind: 'literal', text: labelText }
    else if (labelAttr !== undefined) label = { kind: 'expr', expr: labelAttr.value }
    else {
      warnings.push(`<Tab value=${JSON.stringify(value)}>: no \`label\` — the tab bar item falls back to the value as its text. Give it a label.`)
      label = { kind: 'literal', text: value }
    }
    const iconAttr = attrNamed(el, 'icon')
    const iconName = literalString(iconAttr)
    let icon: TabPlan['icon']
    if (iconName !== undefined) {
      const mapped = ICON_MAP[iconName]
      if (mapped === undefined) {
        warnings.push(
          `<Tab icon=${JSON.stringify(iconName)}>: not in the canonical icon map — passing through as a raw SF Symbol id on iOS and rendering the warning glyph on Android. See ICON_MAP in canonical-primitives.ts.`,
        )
        icon = { sf: iconName, material: 'Warning' }
      } else {
        icon = mapped
      }
    } else if (iconAttr !== undefined) {
      warnings.push(`<Tab value=${JSON.stringify(value)} icon={…}>: \`icon\` must be a string literal (a canonical <Icon> name) on iOS/Android — the icon is DROPPED.`)
    }
    tabs.push({
      value,
      label,
      icon,
      testId: literalString(attrNamed(el, 'data-testid')),
      children: el.children.filter((c) => !isBlankText(c)),
    })
  }
  return { tabs, warnings }
}

export type SidebarPlan =
  | { readonly kind: 'view'; readonly children: readonly ChildIR[] }
  | { readonly kind: 'unsupported'; readonly warning: string }

/**
 * `<Split sidebar={…}>` — a JSX element, a fragment, or a zero-arg accessor
 * returning either. A missing or non-JSX sidebar is NAMED: the list pane is
 * the half of the layout the user starts in on a phone.
 */
export function planSplitSidebar(e: JsxElement): SidebarPlan {
  const attr = attrNamed(e, 'sidebar')
  if (attr === undefined) {
    return {
      kind: 'unsupported',
      warning: '<Split>: no `sidebar` — the list pane renders EMPTY on iOS/Android. Pass the list as `sidebar={<…/>}`.',
    }
  }
  let v = attr.value
  if (v.kind === 'arrow' && v.params.length === 0 && (v.stmts === undefined || v.stmts.length === 0)) v = v.body
  if (v.kind === 'jsx-fragment') return { kind: 'view', children: v.children }
  if (v.kind === 'jsx-element') return { kind: 'view', children: [{ kind: 'expr', expr: v }] }
  return {
    kind: 'unsupported',
    warning:
      '<Split sidebar={…}>: only a JSX literal (`sidebar={<List/>}`) or an accessor returning one lowers to native — this sidebar is DROPPED and the list pane renders EMPTY on iOS/Android. Inline the JSX.',
  }
}
