/**
 * Generate the native chart engine — the committed SwiftUI/Compose twin of
 * `@pyreon/charts`' pure geometry engine.
 *
 * Reads the ten engine sources, strips their module plumbing, runs the REAL
 * PMTC transform for both targets, and post-processes the emit into
 * runtime-owned files:
 *
 *   packages/native/runtime-swift/Sources/PyreonRuntime/PyreonChartEngine.swift
 *   packages/native/runtime-kotlin/src/main/kotlin/com/pyreon/runtime/PyreonChartEngine.kt
 *
 * The three draw-list types (`Pt` / `Rect` / `DrawCmd`) are OWNED by the
 * hand-written PyreonChartCanvas files — the generator strips the synthesized
 * declarations and renames every reference to the runtime names
 * (`PyreonChartPt` / `PyreonChartRect` / `PyreonDrawCmd`), so one type serves
 * the geometry and the renderer.
 *
 * ZERO WARNINGS is a hard precondition: a warning here is a construct the
 * compiler silently could not lower, i.e. a gutted function shipped into the
 * runtime — the exact class the descending-loop / logTicks PRs closed. The
 * builder THROWS rather than writing partial output.
 *
 * Determinism: pure function of the engine sources + compiler — an unchanged
 * input regenerates byte-identically (locked by the drift test:
 * src/tests/native-chart-engine-generated.test.ts).
 *
 * Regenerate: bun packages/native/compiler/scripts/gen-chart-engine.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { transform } from '../src/index'
import { parsePyreon } from '../src/parse'
import type { StructIR } from '../src/types'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO = join(HERE, '../../../..')

