/**
 * `lathe init`, run through the bin's `main` against real configs of each
 * generator Lathe migrates from.
 *
 * The fixtures under `fixtures/init/` are shaped the way those tools document
 * their configs (they carry a `.fixture` suffix so this package's typecheck
 * and lint do not try to resolve `orval` / `@kubb/*`). Each case copies one
 * into a fresh directory, runs `lathe init --yes`, and asserts on the files
 * that come out: the written config, the package.json scripts, and a client
 * the first generate actually produced.
 */
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, renameSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { main } from '../cli/main'
import { amendConfig, createConfig, hasLatheSection, requiredPackages, withScripts } from '../cli/init'
import { readExportedConfig, show } from '../cli/init/literal'
import { fromKubb, fromOrval } from '../cli/init/migrate'
import { parseArgv } from '../cli/run'

const HERE = dirname(fileURLToPath(import.meta.url))
const FIXTURES = join(HERE, 'fixtures', 'init')
const PETSTORE = readFileSync(join(HERE, 'fixtures', 'petstore3.json'), 'utf8')

/** A fresh project from a fixture, `.fixture` suffixes stripped, with the petstore spec. */
function project(name: string, specAt = 'petstore.json'): string {
  const root = mkdtempSync(join(tmpdir(), `lathe-init-${name}-`))
  mkdirSync(join(root, '.git'))
  cpSync(join(FIXTURES, name), root, { recursive: true })
  const unsuffix = (dir: string): void => {
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry)
      if (statSync(full).isDirectory()) unsuffix(full)
      else if (entry.endsWith('.fixture')) renameSync(full, full.slice(0, -'.fixture'.length))
    }
  }
  unsuffix(root)
  if (specAt) {
    mkdirSync(dirname(join(root, specAt)), { recursive: true })
    writeFileSync(join(root, specAt), PETSTORE)
  }
  return root
}

async function capture(fn: () => Promise<number>): Promise<{ code: number; out: string; err: string }> {
  const out: string[] = []
  const err: string[] = []
  const o = process.stdout.write.bind(process.stdout)
  const e = process.stderr.write.bind(process.stderr)
  process.stdout.write = ((s: string) => (out.push(String(s)), true)) as typeof process.stdout.write
  process.stderr.write = ((s: string) => (err.push(String(s)), true)) as typeof process.stderr.write
  try {
    const code = await fn()
    return { code, out: out.join(''), err: err.join('') }
  } finally {
    process.stdout.write = o
    process.stderr.write = e
  }
}

const read = (root: string, path: string): string => readFileSync(join(root, path), 'utf8')
const scripts = (root: string): Record<string, string> =>
  (JSON.parse(read(root, 'package.json')) as { scripts?: Record<string, string> }).scripts ?? {}

/** Import the written config back, the way `lathe generate` will. */
async function writtenSection(root: string): Promise<Record<string, unknown>> {
  const mod = (await import(`${join(root, 'pyreon.config.ts')}?t=${Date.now()}`)) as { default: { lathe: Record<string, unknown> } }
  return mod.default.lathe
}

describe('lathe init — from orval', { timeout: 60_000 }, () => {
  it('maps input, hooks, mocks, client and base URL; reports the mutator; writes a client', async () => {
    const root = project('orval')
    const r = await capture(() => main(['init', '--yes', '--no-color'], root))
    expect(r.code, r.err + r.out).toBe(0)

    const lathe = await writtenSection(root)
    expect(lathe).toMatchObject({
      input: './petstore.json',
      client: 'fetch',
      baseUrl: 'https://petstore3.swagger.io/api/v3',
      plugins: ['schemas', 'client', 'queries', 'mocks', 'faker'],
    })
    // `src/api` still holds orval's output, so Lathe writes beside it.
    expect(lathe.output).toBe('./src/gen')
    expect(r.out).toContain('src/api holds orval')
    expect(read(root, 'src/api/petstore.ts')).toContain('generated by orval')

    // What could not be mapped is NAMED, with what to do instead.
    expect(r.out).toContain('petstore.output.override.mutator')
    expect(r.out).toContain('configureApi({ use: [yourMiddleware], headers })')
    expect(r.out).toContain('petstore.hooks')
    expect(r.out).toContain('petstore.output.prettier')

    expect(scripts(root)).toMatchObject({ api: 'orval', 'lathe:generate': 'lathe generate', 'lathe:check': 'lathe check' })
    expect(r.out).toContain('these scripts still run the old generator: api')
    expect(r.out).toMatch(/install {2}npm install @pyreon\/http @pyreon\/query @pyreon\/validate && npm install -D @faker-js\/faker @pyreon\/lathe/)

    // The first generate ran.
    expect(existsSync(join(root, 'src/gen/queries/pet.ts'))).toBe(true)
    expect(existsSync(join(root, 'src/gen/mocks.ts'))).toBe(true)
  })

  it('several APIs become `projects`, a URL input becomes `source`', () => {
    const cfg = readExportedConfig(read(project('orval-multi', ''), 'orval.config.ts'))
    expect(cfg).toBeDefined()
    const [remote, zod] = fromOrval(cfg!, 'orval.config.ts')
    expect(remote?.name).toBe('petstore')
    expect(remote?.section).toMatchObject({
      source: 'https://petstore3.swagger.io/api/v3/openapi.json',
      input: './openapi.json',
      output: './src/petstore',
      client: 'axios',
    })
    expect(zod?.section).toMatchObject({ input: './petstore.json', validator: 'zod', output: './src/zod' })
    expect(zod?.unmapped.map((u) => u.from)).toEqual(['petstoreZod.input.filters', 'petstoreZod.output....'])
  })
})

