describe('lathe init — from kubb', { timeout: 60_000 }, () => {
  it('reads the object a defineConfig FUNCTION returns, and maps its plugin calls', async () => {
    const root = project('kubb')
    const r = await capture(() => main(['init', '--yes', '--no-generate', '--no-color'], root))
    expect(r.code, r.err + r.out).toBe(0)
    expect(await writtenSection(root)).toMatchObject({
      input: './petstore.json',
      client: 'axios',
      validator: 'zod',
      baseUrl: 'https://petstore3.swagger.io/api/v3',
      plugins: ['schemas', 'client', 'queries', 'mocks', 'faker'],
    })
    // `./src/gen` is empty here, so kubb's own output path is kept.
    expect((await writtenSection(root)).output).toBe('./src/gen')
    const [m] = fromKubb(readExportedConfig(read(root, 'kubb.config.ts'))!, 'kubb.config.ts')
    expect(m?.unmapped.map((u) => u.from)).toEqual([
      'plugins[2] pluginClient.dataReturnType',
      'plugins[3] pluginReactQuery.suspense',
    ])
    expect(scripts(root)).toMatchObject({ generate: 'kubb generate', 'lathe:generate': 'lathe generate' })
  })

  it('a config it cannot read names the file and the way out, and writes nothing', async () => {
    const root = project('kubb')
    writeFileSync(join(root, 'kubb.config.ts'), "import { build } from './build'\nexport default build(process.env)\n")
    const r = await capture(() => main(['init', '--yes', '--no-color'], root))
    expect(r.code).toBe(1)
    expect(r.err).toContain('could not read kubb.config.ts')
    expect(r.err).toContain('lathe init ./openapi.yaml')
    expect(existsSync(join(root, 'pyreon.config.ts'))).toBe(false)
  })
})

