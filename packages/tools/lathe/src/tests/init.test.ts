describe('lathe init — from a bare spec', { timeout: 60_000 }, () => {
  it('finds api/openapi.json, and --dry-run writes nothing', async () => {
    const root = project('bare', 'api/openapi.json')
    const r = await capture(() => main(['init', '--yes', '--dry-run', '--no-color'], root))
    expect(r.code, r.err).toBe(0)
    expect(r.out).toContain('from an OpenAPI document (api/openapi.json)')
    expect(r.out).toContain('dry run: nothing was written.')
    expect(existsSync(join(root, 'pyreon.config.ts'))).toBe(false)
    expect(scripts(root)).toEqual({})
  })

  it('`--json` is one document, with the first generate inside it', async () => {
    const root = project('bare', 'api/openapi.json')
    const r = await capture(() => main(['init', '--yes', '--json'], root))
    expect(r.code, r.err).toBe(0)
    const doc = JSON.parse(r.out) as { ok: boolean; command: string; section: { input: string }; generated: { ok: boolean } }
    expect(doc).toMatchObject({ ok: true, command: 'init', section: { input: './api/openapi.json' }, generated: { ok: true } })
  })

  it('with nothing to find, and no one to ask, it says what to pass', async () => {
    const root = project('bare', '')
    const r = await capture(() => main(['init', '--yes'], root))
    expect(r.code).toBe(1)
    expect(r.err).toContain('lathe init ./openapi.yaml')
  })
})

describe('lathe init — an existing pyreon.config.ts', { timeout: 60_000 }, () => {
  it('adds `lathe` to it, keeps everything else, and keeps a script the user already has', async () => {
    const root = project('amend')
    const before = read(root, 'pyreon.config.ts')
    const r = await capture(() => main(['init', './petstore.json', '--yes', '--no-generate', '--no-color'], root))
    expect(r.code, r.err + r.out).toBe(0)
    const after = read(root, 'pyreon.config.ts')
    expect(after).toContain("atlas: {\n    title: 'My app',\n  },")
    expect(after).toContain("import { defineConfig } from '@pyreon/config'")
    // Exactly one entry inserted; every other byte as it was.
    expect(after).toBe(before.replace('defineConfig({', "defineConfig({\n  lathe: { input: './petstore.json', output: './src/gen' },"))
    expect(scripts(root)['lathe:generate']).toBe('lathe generate --target multiplatform')
    expect(r.out).toContain('kept your own lathe:generate')
  })

  it('never replaces a lathe section that is already there', async () => {
    const root = project('amend')
    writeFileSync(join(root, 'pyreon.config.ts'), "export default { lathe: { input: './mine.yaml' } }\n")
    const r = await capture(() => main(['init', './petstore.json', '--yes'], root))
    expect(r.code).toBe(1)
    expect(r.err).toContain('already has a `lathe` section')
    expect(read(root, 'pyreon.config.ts')).toBe("export default { lathe: { input: './mine.yaml' } }\n")
  })
})

describe('init building blocks', () => {
  it('the literal reader keeps what it cannot evaluate as text', () => {
    const cfg = readExportedConfig(`
      // comment with a { brace
      export default {
        input: \`./spec.yaml\`,
        target: process.env.TARGET ?? 'web',
        list: [1, 'two', true, null],
        fn: plugin({ a: 1 }),
        tpl: \`\${x}/y\`,
      } satisfies Config
    `)
    expect(show(cfg!)).toBe(
      '{ input: "./spec.yaml", target: process.env.TARGET ?? \'web\', list: [1, "two", true, null], fn: plugin({ a: 1 }), tpl: `${x}/y` }',
    )
  })

  it('follows `export default config` to its declaration', () => {
    expect(show(readExportedConfig("const config = { a: 'b' }\nexport default config")!)).toBe('{ a: "b" }')
  })

  it('amends only the exported object, or refuses', () => {
    expect(amendConfig('export default {}\n', { input: './a.yaml' })).toBe("export default {\n  lathe: { input: './a.yaml' },\n}\n")
    expect(amendConfig('const c = {}\nexport default c\n', { input: './a.yaml' })).toBeUndefined()
    expect(hasLatheSection("export default { 'lathe': {} }")).toBe(true)
    expect(hasLatheSection('export default { /* lathe: later */ atlas: {} }')).toBe(false)
  })

  it('writes a config that loads', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'lathe-init-create-'))
    writeFileSync(join(dir, 'pyreon.config.ts'), createConfig({ input: './a.yaml', plugins: ['schemas'] }))
    expect(await writtenSection(dir)).toEqual({ input: './a.yaml', plugins: ['schemas'] })
  })

  it('keeps package.json formatting', () => {
    expect(withScripts('{\n    "name": "x"\n}\n', { a: 'b' })).toBe('{\n    "name": "x",\n    "scripts": {\n        "a": "b"\n    }\n}\n')
  })

  it('lists the packages the generated code imports', () => {
    expect(requiredPackages({ input: 'x' })).toEqual({ runtime: ['@pyreon/http', '@pyreon/query', '@pyreon/validate'], dev: ['@pyreon/lathe'] })
    expect(requiredPackages({ input: 'x', client: 'axios', validator: 'zod', plugins: ['schemas', 'client'] }).runtime).toEqual([
      '@pyreon/http',
      'axios',
      'zod',
    ])
  })

  it('parses its flags, and refuses them on other commands', () => {
    expect(parseArgv(['init', './a.yaml', '--from', 'orval', '-y', '--no-generate'])).toMatchObject({
      command: 'init',
      input: './a.yaml',
      from: 'orval',
      yes: true,
      noGenerate: true,
      errors: [],
    })
    expect(parseArgv(['init', '--from', 'orvel']).errors[0]).toContain('Did you mean `orval`?')
    expect(parseArgv(['generate', '--yes']).errors).toEqual(['`--from`, `--yes` and `--no-generate` only apply to `lathe init`.'])
  })
})
