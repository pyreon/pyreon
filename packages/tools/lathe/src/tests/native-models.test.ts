/**
 * The `swift` / `kotlin` plugins: plain native model types from the spec
 * (#4836). The emitted TEXT, the config surface, and the file bookkeeping
 * (`lathe check`, the manifest). The real-compiler half is
 * `native-models-toolchain.test.ts`.
 */
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgv, run, type Fs } from '../cli/run'
import { ALL_PLUGINS, resolveConfig } from '../core/config'
import { formatFiles } from '../core/format'
import { generate } from '../core/generate'
import { KOTLIN_MODELS_PATH, SWIFT_MODELS_PATH, lowerModels } from '../emit/native-models'

const SPEC = readFileSync(join(dirname(fileURLToPath(import.meta.url)), 'fixtures', 'native-models.json'), 'utf8')

const gen = (section: Parameters<typeof resolveConfig>[0] = {}) =>
  generate(SPEC, resolveConfig({ input: 'x', plugins: ['swift', 'kotlin'], ...section }))

const fileOf = (out: ReturnType<typeof gen>, path: string) => out.files.find((f) => f.path === path)?.contents as string

const out = gen()
const swift = fileOf(out, SWIFT_MODELS_PATH)
const kotlin = fileOf(out, KOTLIN_MODELS_PATH)

describe('selection', () => {
  it('is two built-in plugins with no TypeScript requirements', () => {
    expect(ALL_PLUGINS).toContain('swift')
    expect(ALL_PLUGINS).toContain('kotlin')
    expect(resolveConfig({ input: 'x', plugins: ['swift'] }).plugins).toEqual(['swift'])
  })

  it('writes swift/Models.swift and kotlin/Models.kt and no TypeScript client', () => {
    const paths = out.files.map((f) => f.path)
    expect(paths).toContain(SWIFT_MODELS_PATH)
    expect(paths).toContain(KOTLIN_MODELS_PATH)
    expect(paths.some((p) => p.startsWith('schemas') || p === 'client.ts')).toBe(false)
  })

  it('is not emitted by default', () => {
    const def = generate(SPEC, resolveConfig({ input: 'x' })).files.map((f) => f.path)
    expect(def).not.toContain(SWIFT_MODELS_PATH)
    expect(def).not.toContain(KOTLIN_MODELS_PATH)
  })

  it('is listed in the output manifest, so a dropped plugin prunes its file', () => {
    const manifest = JSON.parse(fileOf(out, 'lathe-manifest.json')) as { files: string[] }
    expect(manifest.files).toContain(SWIFT_MODELS_PATH)
    expect(manifest.files).toContain(KOTLIN_MODELS_PATH)
  })

  it('regenerates byte-identically', () => {
    const again = gen()
    expect(fileOf(again, SWIFT_MODELS_PATH)).toBe(swift)
    expect(fileOf(again, KOTLIN_MODELS_PATH)).toBe(kotlin)
  })
})

describe('format', () => {
  it('never hands a Swift or Kotlin file to the project formatter (prettier cannot parse them)', async () => {
    const seen: string[] = []
    const formatted = await formatFiles(out.files, (code, path) => {
      seen.push(path)
      return code
    })
    expect(seen).toContain('index.ts')
    expect(seen).not.toContain(SWIFT_MODELS_PATH)
    expect(seen).not.toContain(KOTLIN_MODELS_PATH)
    expect(formatted.find((f) => f.path === SWIFT_MODELS_PATH)?.contents).toBe(swift)
  })
})

describe('config', () => {
  it('defaults: Kotlin package `api`, Swift internal', () => {
    expect(resolveConfig({ input: 'x' }).nativeModels).toEqual({ kotlinPackage: 'api', swiftAccess: 'internal' })
    expect(kotlin).toContain('\npackage api\n')
    expect(swift).toContain('\nstruct Pet: Codable {')
  })

  it('takes a package and public access', () => {
    const o = gen({ nativeModels: { kotlinPackage: 'com.example.api', swiftAccess: 'public' } })
    expect(fileOf(o, KOTLIN_MODELS_PATH)).toContain('\npackage com.example.api\n')
    expect(fileOf(o, KOTLIN_MODELS_PATH)).toContain('val value: com.example.api.Circle')
    const s = fileOf(o, SWIFT_MODELS_PATH)
    expect(s).toContain('public struct Pet: Codable {')
    expect(s).toContain('    public var name: String')
    expect(s).toMatch(/ {4}public init\(id: Int, name: String,/)
  })

  it('refuses a package that is not a Kotlin package name, and an unknown access level', () => {
    expect(() => resolveConfig({ input: 'x', nativeModels: { kotlinPackage: 'com.my-app' } })).toThrow(/not a Kotlin package name/)
    expect(() => resolveConfig({ input: 'x', nativeModels: { kotlinPackage: 'com.package.api' } })).toThrow(/not a Kotlin package name/)
    expect(() =>
      resolveConfig({ input: 'x', nativeModels: { swiftAccess: 'open' as unknown as 'public' } }),
    ).toThrow(/swiftAccess/)
  })
})

describe('Swift emit', () => {
  it('starts with the banner and imports only Foundation', () => {
    expect(swift.startsWith('// @generated by @pyreon/lathe from Native Models 1.0.0.\n')).toBe(true)
    expect(swift).toContain('\nimport Foundation\n')
  })

  it('maps required, optional and nullable fields, and snake_case / keyword / symbol keys through CodingKeys', () => {
    expect(swift).toContain('    var name: String\n')
    expect(swift).toContain('    var weight: Double?\n')
    // required + nullable: no default in the init, so the caller must decide
    expect(swift).toContain('nickname: String?,')
    expect(swift).toContain('weight: Double? = nil')
    expect(swift).toContain('        case createdAt = "created_at"')
    expect(swift).toContain('        case class_ = "class"')
    expect(swift).toContain('        case _2faEnabled = "2fa-enabled"')
    expect(swift).toContain('        case price = "price$"')
  })

  it('maps date-time to Date (decoded by LatheJSON), date to String, maps and free JSON', () => {
    expect(swift).toContain('    var createdAt: Date\n')
    expect(swift).toContain('    var birthday: String?\n')
    expect(swift).toContain('    var attributes: [String: Int]?\n')
    expect(swift).toContain('    var metadata: [String: JSONValue]?\n')
    expect(swift).toContain('enum JSONValue: Codable, Hashable {')
    expect(swift).toContain('enum LatheJSON {')
    expect(swift).toContain('.withFractionalSeconds')
  })

  it('hoists inline enums and objects to named types; string and integer enums are raw-value enums', () => {
    expect(swift).toContain('enum PetStatus: String, Codable, Hashable, CaseIterable {')
    expect(swift).toContain('    case inProgress = "in_progress"')
    expect(swift).toContain('    case soldOut = "sold-out"')
    expect(swift).toContain('    case default_ = "default"')
    expect(swift).toContain('enum PetPriority: Int, Codable, Hashable, CaseIterable {')
    expect(swift).toContain('    case valueMinus3 = -3')
    expect(swift).toContain('struct PetOwner: Codable {')
    expect(swift).toContain('typealias Point = [PointItem]')
  })

  it('a single-value enum (a discriminator tag) is a String with the value documented', () => {
    expect(swift).toMatch(/\/\/\/ Always `circle`\.\n {4}var shapeType: String/)
  })

  it('a tagged union dispatches on the discriminator and rejects an unknown tag', () => {
    expect(swift).toContain('indirect enum Shape: Codable {')
    expect(swift).toContain('case tag = "shape_type"')
    expect(swift).toContain('        case "circle":\n            self = .circle(try Circle(from: decoder))')
    expect(swift).toContain('throw DecodingError.dataCorruptedError(forKey: .tag')
  })

  it('an untagged union tries members in order, integers before doubles', () => {
    const contact = swift.slice(swift.indexOf('indirect enum Contact'))
    const order = ['String(from:', 'Int(from:', 'Address(from:', 'Double(from:'].map((s) => contact.indexOf(s))
    expect(order.every((i) => i > 0)).toBe(true)
    expect([...order].sort((a, b) => a - b)).toEqual(order)
  })

  it('allOf merges; a struct on a cycle becomes a final class; readOnly/writeOnly split into <Name>Input', () => {
    expect(swift).toMatch(/struct Dog: Codable \{\n {4}var id: String\n {4}var barks: Bool/)
    expect(swift).toContain('final class Node: Codable {')
    expect(swift).toContain('struct PetInput: Codable {')
    const pet = swift.slice(swift.indexOf('struct Pet: Codable'), swift.indexOf('struct PetInput'))
    expect(pet).not.toContain('secret')
    const input = swift.slice(swift.indexOf('struct PetInput: Codable'))
    expect(input).toContain('var secret: String?')
    expect(input.slice(0, input.indexOf('init('))).not.toContain('var id:')
  })

  it('renames a model whose name the file itself uses', () => {
    expect(swift).toContain('struct ListModel: Codable {')
    expect(swift).not.toMatch(/struct List:/)
  })

  it('a mixed-type enum is the JSON value type; a free-form root is an alias', () => {
    expect(swift).toContain('typealias Mixed = JSONValue')
    expect(swift).toContain('typealias Labels = [String: String]')
    expect(swift).toContain('typealias Ids = [String]')
  })

  it('a description cannot leave its doc comment', () => {
    expect(swift).toContain('/// A pet.\n/// Two lines, and a */ terminator.\nstruct Pet')
  })

  it('omits JSONValue when nothing needs it', () => {
    const small = generate(
      JSON.stringify({
        openapi: '3.0.3',
        info: { title: 'S', version: '1' },
        paths: {},
        components: { schemas: { A: { type: 'object', properties: { a: { type: 'string' } } } } },
      }),
      resolveConfig({ input: 'x', plugins: ['swift', 'kotlin'], filters: { models: 'all' } }),
    )
    expect(fileOf(small, SWIFT_MODELS_PATH)).not.toContain('JSONValue')
    expect(fileOf(small, KOTLIN_MODELS_PATH)).not.toContain('JsonElement')
  })
})

describe('Kotlin emit', () => {
  it('is a @Serializable data class per object, with @SerialName for non-identifier keys', () => {
    expect(kotlin).toContain('@Serializable\ndata class Pet(\n')
    expect(kotlin).toContain('    @SerialName("created_at") val createdAt: String,')
    expect(kotlin).toContain('    @SerialName("class") val class_: String? = null,')
    expect(kotlin).toContain('    @SerialName("2fa-enabled") val _2faEnabled: Boolean? = null,')
    // `$` is a template in a Kotlin string: escaped.
    expect(kotlin).toContain('    @SerialName("price\\$") val price: String? = null,')
  })

  it('maps nullability: optional gets `= null`, required-nullable does not', () => {
    expect(kotlin).toContain('    val nickname: String?,\n')
    expect(kotlin).toContain('    val weight: Double? = null,\n')
    expect(kotlin).toContain('    val id: Long,\n')
  })

  it('string enums are @Serializable enum classes; integer enums are Long with the values documented', () => {
    expect(kotlin).toContain('@Serializable\nenum class PetStatus {')
    expect(kotlin).toContain('    @SerialName("in_progress") IN_PROGRESS,')
    expect(kotlin).toContain('/** One of: 1, 2, -3. */\ntypealias PetPriority = Long')
  })

  it('maps, free JSON, arrays and aliases', () => {
    expect(kotlin).toContain('    val attributes: Map<String, Long>? = null,')
    expect(kotlin).toContain('    val metadata: Map<String, JsonElement>? = null,')
    expect(kotlin).toContain('    val tags: List<String>? = null,')
    expect(kotlin).toContain('typealias Point = List<PointItem>')
    expect(kotlin).toContain('@Serializable\nclass Empty\n')
  })

  it('a union is a sealed interface with a JSON serializer; tagged dispatch qualifies model names', () => {
    expect(kotlin).toContain('@Serializable(with = ShapeSerializer::class)\nsealed interface Shape {')
    expect(kotlin).toContain('    data class Circle(val value: api.Circle) : Shape')
    expect(kotlin).toContain('"circle" -> Shape.Circle(input.json.decodeFromJsonElement<Circle>(element))')
    expect(kotlin).toContain('else -> throw SerializationException("Unknown shape_type ${tag} for Shape")')
  })

  it('an untagged union tries each member in order', () => {
    const body = kotlin.slice(kotlin.indexOf('object ContactSerializer'))
    const order = ['Contact.StringValue(', 'Contact.IntValue(', 'Contact.Address(', 'Contact.DoubleValue('].map((s) => body.indexOf(s))
    expect([...order].sort((a, b) => a - b)).toEqual(order)
  })

  it('ships a Json that ignores unknown keys, like Swift Codable', () => {
    expect(kotlin).toContain('val LatheJson: Json = Json { ignoreUnknownKeys = true }')
  })

  it('a description cannot close its KDoc', () => {
    expect(kotlin).toContain(' * Two lines, and a *\\/ terminator.')
  })
})

describe('lowering', () => {
  it('names a declared discriminator it could not use, rather than dropping it', () => {
    const ir = generate(
      JSON.stringify({
        openapi: '3.0.3',
        info: { title: 'U', version: '1' },
        paths: {},
        components: {
          schemas: {
            A: { type: 'object', required: ['t'], properties: { t: { type: 'string' } } },
            B: { type: 'object', required: ['t'], properties: { t: { type: 'string' } } },
            U: { oneOf: [{ $ref: '#/components/schemas/A' }, { $ref: '#/components/schemas/B' }], discriminator: { propertyName: 't' } },
          },
        },
      }),
      resolveConfig({ input: 'x', plugins: ['swift'], filters: { models: 'all' } }),
    ).doc
    const u = lowerModels(ir).decls.find((d) => d.name === 'U')
    expect(u?.kind).toBe('union')
    if (u?.kind !== 'union') return
    // Either the input layer already demoted it, or the native lowering did --
    // in both cases the union is untagged, never tagged on a free string.
    expect(u.discriminator).toBeUndefined()
  })
})

describe('lathe check', () => {
  const YAML = `
openapi: 3.0.3
info: { title: Notes, version: 1.0.0 }
paths: {}
components:
  schemas:
    Note:
      type: object
      required: [id, title]
      properties:
        id: { type: string }
        title: { type: string }
        body: { type: string }
`
  function memFs(seed: Record<string, string> = {}): Fs & { files: Record<string, string> } {
    const files: Record<string, string> = { 'openapi.yaml': YAML, ...seed }
    return {
      files,
      read: (p) => {
        const v = files[p]
        if (v === undefined) throw new Error(`ENOENT ${p}`)
        return v
      },
      write: (p, c) => {
        files[p] = c
      },
      exists: (p) => p in files,
      mkdirp: () => undefined,
      remove: (p) => {
        delete files[p]
      },
      join: (...parts) => parts.join('/').replace(/\/+/g, '/'),
    }
  }

  it('`--plugins swift,kotlin` writes both files, and check reports a stale native file', async () => {
    const fs = memFs()
    const gen1 = await run(parseArgv(['generate', 'openapi.yaml', '--out', 'gen', '--plugins', 'swift,kotlin']), undefined, fs)
    expect(gen1.code, gen1.stderr).toBe(0)
    expect(fs.files['gen/swift/Models.swift']).toContain('struct Note: Codable {')
    expect(fs.files['gen/kotlin/Models.kt']).toContain('data class Note(')
    const clean = await run(parseArgv(['check', 'openapi.yaml', '--out', 'gen', '--plugins', 'swift,kotlin']), undefined, fs)
    expect(clean.code).toBe(0)
    fs.files['gen/kotlin/Models.kt'] = '// hand-edited'
    const stale = await run(parseArgv(['check', 'openapi.yaml', '--out', 'gen', '--plugins', 'swift,kotlin']), undefined, fs)
    expect(stale.code).toBe(1)
    expect(stale.stdout).toMatch(/~ stale\s+gen\/kotlin\/Models\.kt/)
  })
})
