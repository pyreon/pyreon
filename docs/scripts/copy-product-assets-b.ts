/**
 * Copy the hero visuals of the app-building-blocks and visual-and-tools
 * product pages from the asset set into the docs app.
 *
 *   bun scripts/copy-product-assets-b.ts <path-to-09-site>
 *
 * Reads `assets/manifest.json` (the asset set's own list: file, kind, alt,
 * size, variants) and, for each id below:
 *
 *   - animated SVG (`class="pxa"`, one file for both themes) → two files,
 *     `hero.dark.svg` and `hero.light.svg`, with `data-theme` set on the root.
 *     The SVG's own stylesheet keys its colours on that attribute, so an
 *     `<img>` of each follows the site's theme toggle (an `<img>` cannot see
 *     the page's `<html data-theme>`) and ships no JavaScript.
 *   - real capture (`hero-dark.png` + `hero-light.png` pair) → only the
 *     AVIF/WebP width variants (640, 1280, 1920), never the PNG masters.
 *
 * and writes `src/site/demos/_asset-b.generated.ts` with each hero's kind,
 * size and alt text, so no alt text is hand-copied. Re-run after the asset
 * set changes. Until the home slice's shared asset helpers land, this and
 * `_asset-b.tsx` are the one place these pages reference assets from.
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

export const IDS_B = [
  'feature', 'i18n', 'permissions', 'urlstate', 'hotkeys', 'rx', 'dnd', 'toast', 'table', 'virtual',
  'charts', 'editor', 'flow', 'document', 'atlas', 'lathe', 'loom', 'tooling', 'ai', 'migrate',
] as const

interface Variant { file: string; width: number; height: number; format: string }
interface Asset {
  file: string
  kind: string
  slot?: string
  alt?: string
  theme?: string
  pair?: string
  width: number
  height: number
  variantFiles?: Variant[]
}

const source = process.argv[2]
if (!source) {
  process.stderr.write('[Pyreon] usage: bun scripts/copy-product-assets-b.ts <path-to-09-site>\n')
  process.exit(1)
}
const assets = resolve(source, 'assets')
const manifest = JSON.parse(readFileSync(join(assets, 'manifest.json'), 'utf8')) as { assets: Asset[] }
const docs = resolve(import.meta.dir, '..')
const pub = join(docs, 'public/assets')

const put = (rel: string, data?: string) => {
  const dest = join(pub, rel)
  mkdirSync(dirname(dest), { recursive: true })
  if (data === undefined) copyFileSync(join(assets, rel), dest)
  else writeFileSync(dest, data)
}

type Hero =
  | { kind: 'svg'; width: number; height: number; alt: string; dark: string; light: string }
  | { kind: 'capture'; width: number; height: number; alt: string; dark: Variant[]; light: Variant[] }

const heroes: Record<string, Hero> = {}
for (const id of IDS_B) {
  const svg = manifest.assets.find((a) => a.file === `products/${id}/hero.svg`)
  const dark = manifest.assets.find((a) => a.file === `products/${id}/hero-dark.png`)
  const light = manifest.assets.find((a) => a.file === `products/${id}/hero-light.png`)
  if (svg) {
    const raw = readFileSync(join(assets, svg.file), 'utf8')
    if (!/^<svg[^>]*class="pxa/.test(raw)) throw new Error(`[Pyreon] ${svg.file} is not a theme-aware (pxa) SVG`)
    for (const mode of ['dark', 'light'] as const) {
      put(`products/${id}/hero.${mode}.svg`, raw.replace(/^<svg /, `<svg data-theme="${mode}" `))
    }
    heroes[id] = {
      kind: 'svg',
      width: svg.width,
      height: svg.height,
      alt: svg.alt ?? '',
      dark: `/assets/products/${id}/hero.dark.svg`,
      light: `/assets/products/${id}/hero.light.svg`,
    }
  } else if (dark && light) {
    const pick = (a: Asset) =>
      (a.variantFiles ?? []).filter((v) => /-(640|1280|1920)\.(avif|webp)$/.test(v.file)).map((v) => ({ file: `/assets/${v.file}`, width: v.width, height: v.height, format: v.format }))
    for (const a of [dark, light]) for (const v of pick(a)) put(v.file.slice('/assets/'.length))
    heroes[id] = { kind: 'capture', width: dark.width, height: dark.height, alt: dark.alt ?? '', dark: pick(dark), light: pick(light) }
  } else {
    throw new Error(`[Pyreon] no hero visual for ${id} in the manifest`)
  }
  if (!heroes[id]?.alt) throw new Error(`[Pyreon] the hero visual of ${id} has no alt text in the manifest`)
}

const out = join(docs, 'src/site/demos/_asset-b.generated.ts')
writeFileSync(
  out,
  `// Generated by scripts/copy-product-assets-b.ts from the asset set's manifest.json. Do not edit.\n` +
    `import type { HeroAsset } from './_asset-b'\n\n` +
    `export const HEROES_B: Readonly<Record<string, HeroAsset>> = ${JSON.stringify(heroes, null, 2)}\n`,
)
process.stdout.write(`Copied ${IDS_B.length} hero visuals into public/assets/products and wrote ${out.replace(`${docs}/`, '')}.\n`)
if (!existsSync(pub)) process.exit(1)
