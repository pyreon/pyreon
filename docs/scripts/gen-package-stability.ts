#!/usr/bin/env bun
/**
 * Generate the package tiers from each published package.json's
 * `"pyreon": { "stability", "experimentalSubpaths" }` field (the single source
 * of truth, gated by `scripts/check-stability-tier.ts`):
 *
 *   - `docs/src/mdx/package-stability.generated.ts`, which `<PackageBadge>` reads;
 *   - the tier table between the `gen:package-tiers` markers in
 *     `docs/src/content/docs/stability-and-direction.md`.
 *
 * Never hand-edit either output; run `bun docs/scripts/gen-all.ts`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { readStabilityTable } from '../../scripts/check-stability-tier'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
// The per-platform compiler binaries follow `@pyreon/compiler` and have no page.
const entries = [...readStabilityTable(root).entries()]
  .filter(([name]) => !name.startsWith('@pyreon/compiler-'))
  .sort(([a], [b]) => a.localeCompare(b, 'en'))

// 1. Badge data.
const out = [
  '// GENERATED by docs/scripts/gen-package-stability.ts from every published',
  '// package.json `pyreon.stability` field. Do not edit; run',
  '// `bun docs/scripts/gen-all.ts`.',
  '',
  "export type PackageStability = 'stable' | 'experimental'",
  '',
  'export const PACKAGE_STABILITY: Readonly<Record<string, PackageStability>> = {',
  ...entries.map(([name, field]) => `  '${name}': '${field.stability}',`),
  '}',
  '',
].join('\n')
writeFileSync(join(root, 'docs/src/mdx/package-stability.generated.ts'), out)

// 2. Tier table on the policy page.
const START = '{/* gen:package-tiers:start */}'
const END = '{/* gen:package-tiers:end */}'
const experimental = entries.filter(([, f]) => f.stability === 'experimental').map(([n]) => n)
const withSubpaths = entries.filter(([, f]) => f.stability === 'stable' && (f.experimentalSubpaths?.length ?? 0) > 0)
const stableCount = entries.length - experimental.length
const nativeOnly = withSubpaths.filter(([, f]) => f.experimentalSubpaths?.join() === './native-plugin').map(([n]) => n)
const otherSubpaths = withSubpaths.filter(([, f]) => f.experimentalSubpaths?.join() !== './native-plugin')
const table = [
  START,
  '',
  `Of the ${entries.length} published packages (not counting the per-platform \`@pyreon/compiler-*\` binaries, which follow \`@pyreon/compiler\`), ${stableCount} are Stable and ${experimental.length} are Experimental. This list is generated from each package's \`package.json\`.`,
  '',
  `**Experimental packages (${experimental.length}):** ${experimental.map((n) => `\`${n}\``).join(', ')}.`,
  '',
  '**Stable packages with experimental subpaths:**',
  '',
  '| Package | Experimental subpaths |',
  '| --- | --- |',
  ...otherSubpaths.map(([n, f]) => `| \`${n}\` | ${(f.experimentalSubpaths ?? []).map((s) => `\`${s}\``).join(', ')} |`),
  `| ${nativeOnly.length} more packages | \`./native-plugin\` only: ${nativeOnly.map((n) => `\`${n}\``).join(', ')} |`,
  '',
  END,
].join('\n')
const pagePath = join(root, 'docs/src/content/docs/stability-and-direction.md')
const page = readFileSync(pagePath, 'utf8')
const a = page.indexOf(START)
const b = page.indexOf(END)
if (a === -1 || b === -1) {
  console.error(`[gen-package-stability] ${pagePath} is missing the ${START} / ${END} markers`)
  process.exit(1)
}
writeFileSync(pagePath, page.slice(0, a) + table + page.slice(b + END.length))
console.warn(`[gen-package-stability] ${entries.length} packages (${stableCount} stable, ${experimental.length} experimental)`)
